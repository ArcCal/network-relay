//! Serialized ownership of one global capture session. OS peer identity must
//! come from getpeereid, never from the JSON request or a client-provided PID.
use crate::protocol::{Plan, Request};
use anyhow::{Context, Result, ensure};
use serde::Serialize;

pub trait Backend {
    /// Create utun and physical endpoint bypasses; do not activate capture yet.
    fn prepare(&mut self, plan: &Plan) -> Result<String>;
    /// Install capture and DNS only after the application reports relay readiness.
    fn activate(&mut self, plan: &Plan, interface: &str) -> Result<()>;
    /// Discover physical paths and refresh owned bypasses without client commands.
    fn refresh(&mut self) -> Result<()>;
    /// Restore only owned state. Preserve failed operations in a durable journal.
    fn cleanup(&mut self) -> Result<()>;
}
#[derive(Clone, Debug, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum State {
    Idle,
    Prepared,
    Active,
    RecoveryRequired,
}
#[derive(Clone, Debug, Serialize)]
pub struct Status {
    pub state: State,
    pub interface: Option<String>,
    pub lease: Option<String>,
}
struct Session {
    plan: Plan,
    interface: String,
    lease: String,
}
pub struct Broker<B> {
    owner: u32,
    backend: B,
    session: Option<Session>,
    state: State,
}
impl<B: Backend> Broker<B> {
    /// Startup always requires recovery before accepting a new capture session.
    pub fn new(owner: u32, backend: B) -> Result<Self> {
        ensure!(owner != 0, "broker must be bound to an unprivileged account");
        Ok(Self { owner, backend, session: None, state: State::RecoveryRequired })
    }
    pub fn status(&self) -> Status {
        Status {
            state: self.state.clone(),
            interface: self.session.as_ref().map(|s| s.interface.clone()),
            lease: self.session.as_ref().map(|s| s.lease.clone()),
        }
    }
    fn check_lease(&self, lease: &str) -> Result<()> {
        ensure!(self.session.as_ref().is_some_and(|s| s.lease == lease), "stale or unknown lease");
        Ok(())
    }
    fn cleanup(&mut self) -> Result<()> {
        self.state = State::RecoveryRequired;
        self.backend.cleanup().context("network restoration incomplete")?;
        self.session = None;
        self.state = State::Idle;
        Ok(())
    }
    /// nonce is generated by the broker process using OS randomness, not IPC.
    pub fn handle(
        &mut self,
        peer_uid: u32,
        request: Request,
        nonce: impl FnOnce() -> Result<String>,
    ) -> Result<Status> {
        ensure!(peer_uid == self.owner, "unauthorized peer");
        match request {
            Request::Status => {}
            Request::Recover => {
                self.cleanup()?;
            }
            Request::Stop { lease } => {
                self.check_lease(&lease)?;
                self.cleanup()?;
            }
            Request::Prepare { plan } => {
                ensure!(self.state == State::Idle, "stop or recover the existing session first");
                plan.validate()?;
                let lease = nonce()?;
                ensure!(lease.len() == 64 && lease.bytes().all(|b| b.is_ascii_hexdigit()), "invalid generated lease");
                self.state = State::RecoveryRequired;
                let interface = match self.backend.prepare(&plan) {
                    Ok(interface) => interface,
                    Err(error) => {
                        if let Err(recovery) = self.cleanup() {
                            return Err(error.context(format!("rollback failed: {recovery:#}")));
                        }
                        return Err(error);
                    }
                };
                if !interface
                    .strip_prefix("utun")
                    .is_some_and(|s| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit()))
                {
                    self.cleanup()?;
                    anyhow::bail!("invalid prepared interface");
                }
                self.session = Some(Session { plan, interface, lease });
                self.state = State::Prepared;
            }
            Request::Activate { lease } => {
                self.check_lease(&lease)?;
                ensure!(self.state == State::Prepared, "capture is not prepared");
                let session = self.session.as_ref().unwrap();
                if let Err(error) = self.backend.activate(&session.plan, &session.interface) {
                    if let Err(recovery) = self.cleanup() {
                        return Err(error.context(format!("rollback failed: {recovery:#}")));
                    }
                    return Err(error);
                }
                self.state = State::Active;
            }
            Request::Refresh { lease } => {
                self.check_lease(&lease)?;
                ensure!(matches!(self.state, State::Prepared | State::Active), "recovery required");
                if let Err(error) = self.backend.refresh() {
                    // No persistent kill switch: restore capture if physical
                    // bypass maintenance fails, retaining recovery failures.
                    if let Err(recovery) = self.cleanup() {
                        return Err(error.context(format!("rollback failed: {recovery:#}")));
                    }
                    return Err(error);
                }
            }
        }
        Ok(self.status())
    }
    /// The control connection owns the lease. A late disconnect from an older
    /// connection must not tear down a replacement session.
    pub fn disconnected(&mut self, peer_uid: u32, lease: &str) -> Result<()> {
        ensure!(peer_uid == self.owner, "unauthorized peer");
        if self.session.as_ref().is_some_and(|s| s.lease == lease) {
            self.cleanup()?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::{Arc, Mutex};
    #[derive(Default)]
    struct Fake {
        events: Arc<Mutex<Vec<&'static str>>>,
        fail_activate: bool,
        fail_cleanup: bool,
        fail_refresh: bool,
    }
    impl Backend for Fake {
        fn prepare(&mut self, _: &Plan) -> Result<String> {
            self.events.lock().unwrap().push("bypass");
            Ok("utun8".into())
        }
        fn activate(&mut self, _: &Plan, _: &str) -> Result<()> {
            self.events.lock().unwrap().push("capture");
            ensure!(!self.fail_activate, "injected capture failure");
            Ok(())
        }
        fn refresh(&mut self) -> Result<()> {
            ensure!(!self.fail_refresh, "physical path unavailable");
            Ok(())
        }
        fn cleanup(&mut self) -> Result<()> {
            self.events.lock().unwrap().push("restore");
            ensure!(!self.fail_cleanup, "injected restoration failure");
            Ok(())
        }
    }
    fn nonce() -> Result<String> {
        Ok("a".repeat(64))
    }
    fn plan() -> Plan {
        Plan {
            endpoints: vec!["192.0.2.1".parse().unwrap()],
            resolvers: vec!["1.1.1.1".parse().unwrap()],
            mtu: 1500,
            socks_port: 1080,
        }
    }
    fn prepare(b: &mut Broker<Fake>) {
        b.handle(501, Request::Recover, nonce).unwrap();
        b.handle(501, Request::Prepare { plan: plan() }, nonce).unwrap();
    }
    #[test]
    fn startup_recovery_and_bypass_precede_capture() {
        let fake = Fake::default();
        let events = fake.events.clone();
        let mut b = Broker::new(501, fake).unwrap();
        assert!(b.handle(501, Request::Prepare { plan: plan() }, nonce).is_err());
        prepare(&mut b);
        assert_eq!(b.status().state, State::Prepared);
        assert_eq!(*events.lock().unwrap(), ["restore", "bypass"]);
        b.handle(501, Request::Activate { lease: nonce().unwrap() }, nonce).unwrap();
        assert_eq!(b.status().state, State::Active);
        b.disconnected(501, &nonce().unwrap()).unwrap();
        assert_eq!(*events.lock().unwrap(), ["restore", "bypass", "capture", "restore"]);
        assert_eq!(b.status().state, State::Idle);
    }
    #[test]
    fn wrong_identity_and_stale_lease_do_not_mutate_network() {
        let fake = Fake::default();
        let events = fake.events.clone();
        let mut b = Broker::new(501, fake).unwrap();
        prepare(&mut b);
        assert!(b.handle(502, Request::Recover, nonce).is_err());
        assert!(b.handle(502, Request::Status, nonce).is_err());
        assert!(b.handle(501, Request::Activate { lease: "b".repeat(64) }, nonce).is_err());
        b.disconnected(501, &"b".repeat(64)).unwrap();
        assert_eq!(*events.lock().unwrap(), ["restore", "bypass"]);
        assert_eq!(b.status().state, State::Prepared);
    }
    #[test]
    fn activation_failure_rolls_back_and_failed_rollback_blocks_new_capture() {
        for fail_cleanup in [false, true] {
            let mut b = Broker::new(501, Fake::default()).unwrap();
            prepare(&mut b);
            b.backend.fail_activate = true;
            b.backend.fail_cleanup = fail_cleanup;
            assert!(b.handle(501, Request::Activate { lease: nonce().unwrap() }, nonce).is_err());
            assert_eq!(b.status().state, if fail_cleanup { State::RecoveryRequired } else { State::Idle });
            if fail_cleanup {
                assert!(b.handle(501, Request::Prepare { plan: plan() }, nonce).is_err());
                b.backend.fail_cleanup = false;
                b.handle(501, Request::Recover, nonce).unwrap();
                assert_eq!(b.status().state, State::Idle);
            }
        }
    }
    #[test]
    fn physical_path_failure_restores_instead_of_persistently_blocking_network() {
        let mut b = Broker::new(501, Fake::default()).unwrap();
        prepare(&mut b);
        b.handle(501, Request::Activate { lease: nonce().unwrap() }, nonce).unwrap();
        b.backend.fail_refresh = true;
        assert!(b.handle(501, Request::Refresh { lease: nonce().unwrap() }, nonce).is_err());
        assert_eq!(b.status().state, State::Idle);
    }
}
