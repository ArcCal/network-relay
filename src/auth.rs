        let user = auth.verify(Some(header.as_bytes()), &conn.client()).await.unwrap();
        assert_eq!(conn.bound.lock().unwrap().as_ref().map(|(_, u)| u.clone()), Some(user));
        auth.cache.lock().unwrap().clear();
        // With every hashing slot taken, only a check that needs no hash can finish.
