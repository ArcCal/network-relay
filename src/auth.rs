    struct Conn {
        pending: AtomicUsize,
        bound: Mutex<Option<(CacheTag, User)>>,
        ip: IpAddr,
    }

    impl Conn {
        fn new() -> Self {
            Self::from("192.0.2.1")
        }

        fn from(ip: &str) -> Self {
            Self { pending: AtomicUsize::new(0), bound: Mutex::new(None), ip: ip.parse().unwrap() }
        }

        fn client(&self) -> Client<'_> {
            Client { ip: self.ip, pending: &self.pending, bound: &self.bound }
        }
    }

    async fn check(auth: &Arc<Authenticator>, header: &str) -> Result<User, Denied> {
        auth.verify(Some(header.as_bytes()), &Conn::new().client()).await
    }

    #[test]
    fn basic_header_round_trip() {
        let header = basic_authorization("laptop", "p:a ss");
        assert!(header.starts_with("Basic "));
        assert_eq!(parse_basic(header.as_bytes()), Some(("laptop".into(), "p:a ss".into())));
        // RFC 7617 example.
        assert_eq!(parse_basic(b"Basic QWxhZGRpbjpvcGVuIHNlc2FtZQ=="), Some(("Aladdin".into(), "open sesame".into())));
        assert_eq!(parse_basic(b"basic QWxhZGRpbjpvcGVuIHNlc2FtZQ==").unwrap().0, "Aladdin");
        for bad in [&b"Bearer abc"[..], b"Basic", b"Basic !!!", b"Basic bm9jb2xvbg==", b"\xff\xfe"] {
            assert_eq!(parse_basic(bad), None, "{bad:?}");
        }
    }

