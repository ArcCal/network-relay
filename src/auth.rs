    #[tokio::test]
    async fn cancelled_verification_cleans_up_and_keeps_hash_slot() {
        use std::future::Future;
        use std::task::Poll;
        let auth = Arc::new(Authenticator::new(&[user("alice", "alice-password")]).unwrap());
        let slots = auth.slots.available_permits();
        // Keep every hashing thread busy, so the verification below waits in
        // the queue and the assertions cannot race with it finishing.
        let (release, waiting) = std::sync::mpsc::channel::<()>();
        let waiting = Arc::new(Mutex::new(waiting));
        let (started, ready) = std::sync::mpsc::channel();
        for _ in 0..slots {
            let (waiting, started) = (waiting.clone(), started.clone());
            auth.hashers.spawn(move || {
                started.send(()).unwrap();
                let _ = waiting.lock().unwrap().recv();
            });
        }
        for _ in 0..slots {
            ready.recv().unwrap();
        }
        let header = basic_authorization("alice", "alice-password");
        let conn = Conn::new();
        let client = conn.client();
        let mut verification = Box::pin(auth.verify(Some(header.as_bytes()), &client));
        std::future::poll_fn(|cx| {
            assert!(verification.as_mut().poll(cx).is_pending());
            Poll::Ready(())
        })
        .await;
        drop(verification);
        assert!(auth.inflight.lock().unwrap().is_empty());
        assert_eq!(conn.pending.load(Ordering::Relaxed), 0, "the connection's pending count is released");
        assert_eq!(auth.slots.available_permits(), slots - 1, "the queued hash keeps its slot");
        drop(release);
        let _permit = auth.slots.clone().acquire_many_owned(slots as u32).await.unwrap();
    }

    #[tokio::test]
    async fn verifications_are_cached_and_survive_unchanged_reloads() {
        let alice = user("alice", "alice-password");
        let auth = Arc::new(Authenticator::new(std::slice::from_ref(&alice)).unwrap());
        let good = basic_authorization("alice", "alice-password");
        let bad = basic_authorization("alice", "wrong");
        let first = std::time::Instant::now();
        assert!(check(&auth, &good).await.is_ok());
        let uncached = first.elapsed();
        let second = std::time::Instant::now();
        for _ in 0..20 {
            assert!(check(&auth, &good).await.is_ok());
        }
        assert!(second.elapsed() < uncached, "20 cached checks should beat one hash");
        assert!(check(&auth, &bad).await.is_err());
        assert!(check(&auth, &bad).await.is_err());
        assert_eq!(auth.cache.lock().unwrap().len(), 2);
        assert!(auth.inflight.lock().unwrap().is_empty());
        // Reloading with alice unchanged keeps her verified entry and drops
        // the rejection (a new user or password could make it valid).
        let bob = user("bob", "bob-password");
        auth.replace(&[alice.clone(), bob]).unwrap();
        assert_eq!(auth.cache.lock().unwrap().len(), 1);
        assert!(auth.cached(&auth.tag(good.as_bytes())).is_some_and(|u| u.is_some()));
        // A new password works at once and the old one stops at once.
        auth.replace(&[user("alice", "wrong")]).unwrap();
        assert!(auth.cache.lock().unwrap().is_empty());
        assert!(check(&auth, &bad).await.is_ok(), "the new password works at once");
        assert!(check(&auth, &good).await.is_err(), "the old one stops working at once");
    }

