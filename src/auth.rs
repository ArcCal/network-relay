//! User authentication: passwords (HTTP Basic) and, optionally, client
//! certificates.
//!
//! Apple devices send the header fields configured in the relay profile
//! (`AdditionalHTTPHeaderFields`) with every CONNECT request, so the profile
//! carries an `Authorization` header with HTTP Basic credentials (RFC 7617).
//! Classic HTTP proxy clients such as curl send the same credentials in
//! `Proxy-Authorization` (RFC 9110 §11.7.2); both are accepted. The TLS
//! connection protects the password. The server stores only password hashes
//! in PHC string format:
//!
//! - `pbkdf2-sha256` for secrets generated by `network-relay passwd`. They
//!   carry 144 random bits, so offline guessing is out of reach whatever the
//!   hash costs; a cheap hash keeps password checks from being a lever for
//!   denial of service.
//! - `argon2id` (RFC 9106) for passwords people choose.
//!
//! A profile can instead carry an identity certificate
//! (`PayloadCertificateUUID`); the relay then recognizes the user by the
//! SHA-256 fingerprint of the certificate the TLS client presented.
//!
//! A device opens a relayed connection for almost every connection an app
//! makes, each a new request with the same credentials. Results are therefore
//! cached (keyed by a keyed hash of the header value, so the cache holds no
//! passwords) and bound to the connection that presented them. Verifications
//! that are not cached are limited per client address and per connection,
//! so anonymous clients cannot keep the server busy hashing.

