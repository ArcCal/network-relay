/// Shortest password `network-relay passwd` accepts from the user.
pub const MIN_PASSWORD_LEN: usize = 12;
/// Shortest secret accepted for the fast hash: 24 base64url characters
/// carry 144 random bits.
pub const MIN_GENERATED_SECRET_LEN: usize = 24;
/// PBKDF2 iterations for generated secrets. Their strength comes from their
/// randomness, not from the work factor.
pub const FAST_HASH_ITERATIONS: u32 = 1000;
const FAST_HASH_ALGORITHM: &str = "pbkdf2-sha256";

/// How long a verified header is trusted without hashing again. Each use
/// extends it, so a device in use is not verified again.
const CACHE_TTL: Duration = Duration::from_secs(600);
/// How long a rejected header is rejected without hashing again, so a device
/// with a wrong password cannot keep the server busy.
const NEGATIVE_TTL: Duration = Duration::from_secs(60);
/// Most cached headers. When full, rejections are no longer cached and verified
/// entries are only dropped as a last resort.
const CACHE_MAX: usize = 4096;
/// Uncached verifications one connection may have under way at once.
pub const PENDING_PER_CONNECTION: usize = 4;
/// Uncached verifications per client address: a burst, then one a second.
/// A device needs one per credential change; a client trying many is
/// refused before anything is hashed.
const ATTEMPT_BURST: f64 = 30.0;
const ATTEMPT_RATE: f64 = 1.0;
/// Client addresses tracked for the limit above.
const ATTEMPT_CLIENTS: usize = 65_536;

/// User names appear in logs and must not contain `:`, which separates the
/// name from the password in Basic credentials.
pub fn validate_user_name(name: &str) -> Result<()> {
    ensure!(
        !name.is_empty()
            && name.len() <= 64
            && name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
            && !name.starts_with('.'),
        "user name must be 1-64 characters of letters, digits, '-', '_' or '.', and not start with '.'"
    );
    Ok(())
}

/// The Authorization header value for Basic credentials.
pub fn basic_authorization(username: &str, password: &str) -> String {
    format!("Basic {}", STANDARD.encode(format!("{username}:{password}")))
}

/// Parses a Basic Authorization header value into user name and password.
pub fn parse_basic(value: &[u8]) -> Option<(String, String)> {
    let value = std::str::from_utf8(value).ok()?.trim();
    let (scheme, token) = value.split_once(' ')?;
    if !scheme.eq_ignore_ascii_case("basic") {
        return None;
    }
    let decoded = STANDARD.decode(token.trim()).ok()?;
    let decoded = String::from_utf8(decoded).ok()?;
    let (user, password) = decoded.split_once(':')?;
    Some((user.to_string(), password.to_string()))
}

fn random_bytes<const N: usize>() -> [u8; N] {
    let mut b = [0u8; N];
    SystemRandom::new().fill(&mut b).expect("system RNG");
    b
}

/// A random password with 144 bits of entropy: out of reach of online and
/// offline guessing.
pub fn generate_password() -> String {
    URL_SAFE_NO_PAD.encode(random_bytes::<18>())
}

/// Argon2id hash of a password a person chose, with the argon2 crate's
/// default parameters (19 MiB, 2 passes, 1 lane: the OWASP recommendation).
pub fn hash_password(password: &str) -> Result<String> {
    let salt = SaltString::encode_b64(&random_bytes::<16>()).map_err(|e| anyhow!("salt: {e}"))?;
    let hash = Argon2::default().hash_password(password.as_bytes(), &salt).map_err(|e| anyhow!("hashing: {e}"))?;
    Ok(hash.to_string())
}

/// PBKDF2-SHA256 hash of a randomly generated secret
/// (`$pbkdf2-sha256$i=1000,l=32$<salt>$<hash>`).
pub fn hash_generated_secret(secret: &str) -> Result<String> {
    ensure!(
        secret.chars().count() >= MIN_GENERATED_SECRET_LEN,
        "a generated secret has at least {MIN_GENERATED_SECRET_LEN} characters"
    );
    let salt = random_bytes::<16>();
    let mut out = [0u8; 32];
    ring::pbkdf2::derive(
        ring::pbkdf2::PBKDF2_HMAC_SHA256,
        NonZeroU32::new(FAST_HASH_ITERATIONS).expect("nonzero"),
        &salt,
        secret.as_bytes(),
        &mut out,
    );
    Ok(format!(
        "${FAST_HASH_ALGORITHM}$i={FAST_HASH_ITERATIONS},l=32${}${}",
        STANDARD_NO_PAD.encode(salt),
        STANDARD_NO_PAD.encode(out)
    ))
}

/// Bounds on hash parameters: a configured hash must not make a single
/// verification arbitrarily expensive.
const ARGON2_MAX_MEMORY_KIB: u32 = 64 * 1024;
const ARGON2_MAX_TIME: u32 = 10;
const ARGON2_MAX_LANES: u32 = 4;
const PBKDF2_MIN_ITERATIONS: u32 = 1000;
const PBKDF2_MAX_ITERATIONS: u32 = 1_000_000;

/// A parsed, supported password hash.
#[derive(Debug, Clone)]
enum Hash {
    Argon2id(String),
    Pbkdf2 { iterations: NonZeroU32, salt: Vec<u8>, hash: Vec<u8> },
}

fn parse_hash(hash: &str) -> Result<Hash> {
    let parsed = PasswordHash::new(hash).map_err(|e| anyhow!("not a valid password hash ({e})"))?;
    match parsed.algorithm.as_str() {
        "argon2id" => {
            ensure!(parsed.salt.is_some() && parsed.hash.is_some(), "password hash needs a salt and output");
            if let Some(version) = parsed.version {
                argon2::Version::try_from(version).map_err(|e| anyhow!("invalid Argon2 version: {e}"))?;
            }
            let params = argon2::Params::try_from(&parsed).map_err(|e| anyhow!("invalid Argon2 parameters: {e}"))?;
            ensure!(
                params.m_cost() <= ARGON2_MAX_MEMORY_KIB
                    && params.t_cost() <= ARGON2_MAX_TIME
                    && params.p_cost() <= ARGON2_MAX_LANES,
                "Argon2 parameters exceed the supported maximum (m={ARGON2_MAX_MEMORY_KIB}, t={ARGON2_MAX_TIME}, \
                 p={ARGON2_MAX_LANES})"
            );
            Ok(Hash::Argon2id(hash.to_string()))
        }
        FAST_HASH_ALGORITHM => {
            ensure!(parsed.version.is_none(), "pbkdf2-sha256 hashes have no version");
            let mut iterations = None;
            for (name, value) in parsed.params.iter() {
                match name.as_str() {
                    "i" => iterations = Some(value.decimal().map_err(|e| anyhow!("pbkdf2 iterations: {e}"))?),
                    "l" => ensure!(value.decimal().ok() == Some(32), "pbkdf2-sha256 output length must be 32"),
                    other => bail!("unknown pbkdf2-sha256 parameter {other}"),
                }
            }
            let iterations = iterations.context("pbkdf2-sha256 hash needs i=<iterations>")?;
            ensure!(
                (PBKDF2_MIN_ITERATIONS..=PBKDF2_MAX_ITERATIONS).contains(&iterations),
                "pbkdf2-sha256 iterations must be between {PBKDF2_MIN_ITERATIONS} and {PBKDF2_MAX_ITERATIONS}"
            );
            let salt = parsed.salt.context("pbkdf2-sha256 hash needs a salt")?;
            let salt = STANDARD_NO_PAD.decode(salt.as_str()).map_err(|e| anyhow!("pbkdf2 salt: {e}"))?;
            ensure!(salt.len() >= 8, "pbkdf2 salt must have at least 8 bytes");
            let hash = parsed.hash.context("pbkdf2-sha256 hash needs an output")?;
            ensure!(hash.len() == 32, "pbkdf2-sha256 output must be 32 bytes");
            Ok(Hash::Pbkdf2 {
                iterations: NonZeroU32::new(iterations).expect("checked"),
                salt,
                hash: hash.as_bytes().to_vec(),
            })
        }
        other => bail!("password hash must use argon2id or pbkdf2-sha256, not {other}"),
    }
}

/// Checks that a configured hash is a supported PHC string within bounds.
pub fn validate_hash(hash: &str) -> Result<()> {
    parse_hash(hash).map(|_| ())
}

fn verify_hash(password: &str, hash: &Hash) -> bool {
    match hash {
        Hash::Argon2id(s) => {
            PasswordHash::new(s).is_ok_and(|h| Argon2::default().verify_password(password.as_bytes(), &h).is_ok())
        }
        Hash::Pbkdf2 { iterations, salt, hash } => {
            ring::pbkdf2::verify(ring::pbkdf2::PBKDF2_HMAC_SHA256, *iterations, salt, password.as_bytes(), hash).is_ok()
        }
    }
}

/// Parses a certificate fingerprint as configured: 64 hex digits, optionally
/// prefixed with `sha256:` and separated by colons.
pub fn parse_fingerprint(text: &str) -> Result<[u8; 32]> {
    let hex: String = text
        .trim()
        .strip_prefix("sha256:")
        .or_else(|| text.trim().strip_prefix("SHA256:"))
        .unwrap_or(text.trim())
        .chars()
        .filter(|c| *c != ':')
        .collect();
    ensure!(
        hex.len() == 64 && hex.bytes().all(|b| b.is_ascii_hexdigit()),
        "a certificate fingerprint is 64 hex digits (SHA-256 of the DER certificate)"
    );
    let mut out = [0u8; 32];
    for (i, byte) in out.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).expect("hex");
    }
    Ok(out)
}

/// The SHA-256 fingerprint of a DER certificate.
pub fn fingerprint(der: &[u8]) -> [u8; 32] {
    ring::digest::digest(&ring::digest::SHA256, der).as_ref().try_into().expect("SHA-256 size")
}

pub fn fingerprint_hex(fp: &[u8; 32]) -> String {
    fp.iter().map(|b| format!("{b:02x}")).collect()
}

/// An authenticated user, as the tunnel records it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct User {
    pub name: String,
    /// What the user authenticated with: their password hash, or
    /// `sha256:<fingerprint>` of their certificate. A reload that changes
    /// it ends the user's tunnels.
    pub credential: String,
    /// When the account stops working, if it expires.
    pub expires: Option<SystemTime>,
}

impl User {
    /// Time left before the account expires, if it does.
    pub fn time_left(&self) -> Option<Duration> {
        self.expires.map(|e| e.duration_since(SystemTime::now()).unwrap_or_default())
    }
}

#[derive(Debug, Clone)]
struct Account {
    password: Option<(String, Hash)>,
    certificate: Option<[u8; 32]>,
    expires: Option<SystemTime>,
}

impl Account {
    fn live(&self) -> bool {
        self.expires.is_none_or(|e| SystemTime::now() < e)
    }
}

#[derive(Default)]
struct Users {
    accounts: HashMap<String, Account>,
    by_certificate: HashMap<[u8; 32], String>,
    /// Every password user has a fast hash, so unknown names are checked
    /// against a fast dummy as well (equal timing either way).
    fast_dummy: bool,
}

impl Users {
    fn holds(&self, user: &User) -> bool {
        let Some(account) = self.accounts.get(&user.name) else { return false };
        if !account.live() {
            return false;
        }
        match user.credential.strip_prefix("sha256:") {
            Some(fp) => account.certificate.is_some_and(|c| fingerprint_hex(&c) == fp),
            None => account.password.as_ref().is_some_and(|(s, _)| *s == user.credential),
        }
    }
}

struct Cached {
    user: Option<User>,
    until: Instant,
}

pub type CacheTag = [u8; 32];

/// Why a request was not authenticated. All of them get the website's
/// answer; the distinction is for logging.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Denied {
    /// No credentials at all.
    Missing,
    /// Not HTTP Basic credentials.
    Malformed,
    /// Wrong name or password, an expired account, or a removed user.
    Rejected { user: String },
    /// Too many verifications from this client or connection, or overall.
    Throttled { user: String },
}

/// Where a request comes from, for the per-client and per-connection
/// limits and for binding credentials to the connection.
pub struct Client<'a> {
    pub ip: IpAddr,
    /// Uncached verifications this connection has under way.
    pub pending: &'a AtomicUsize,
    /// The credentials this connection last authenticated with.
    pub bound: &'a Mutex<Option<(CacheTag, User)>>,
}

/// Verifies credentials against the configured users.
pub struct Authenticator {
    users: RwLock<Users>,
    /// Hashing takes tens of milliseconds and megabytes of memory, so the
    /// number of concurrent verifications is capped.
    slots: Arc<Semaphore>,
    /// Where the hashing runs: threads of its own, one per slot.
    hashers: HashThreads,
    /// Verified instead of a real hash for unknown user names, so the
    /// response time does not reveal which names exist.
    dummy_slow: Hash,
    dummy_fast: Hash,
    /// Keys the cache by HMAC of the header value; random per process.
    cache_key: ring::hmac::Key,
    cache: Mutex<HashMap<CacheTag, Cached>>,
    /// One verification per header at a time: a device's burst of requests
    /// with the same new credentials waits for the first to finish.
    inflight: Mutex<HashMap<CacheTag, Arc<tokio::sync::Mutex<()>>>>,
    /// Uncached verifications per client address.
    attempts: PerIp,
    /// Bumped whenever the user list changes, so tunnels can check whether
    /// their user is still current.
    generation: watch::Sender<u64>,
}

type HashJob = Box<dyn FnOnce() + Send>;

/// Threads that only verify password hashes. A check takes milliseconds of
/// CPU (tens for Argon2id); on tokio's shared blocking pool it would wait
/// behind slow DNS lookups, and they behind it. The threads end when the
/// authenticator is dropped.
struct HashThreads {
    jobs: std::sync::mpsc::Sender<HashJob>,
}

impl HashThreads {
    fn new(threads: usize) -> Result<Self> {
        let (jobs, queue) = std::sync::mpsc::channel::<HashJob>();
        let queue = Arc::new(Mutex::new(queue));
        for i in 0..threads {
            let queue = queue.clone();
            std::thread::Builder::new()
                .name(format!("password-hash-{i}"))
                .spawn(move || loop {
                    let job = queue.lock().unwrap().recv();
                    match job {
                        // A panicking job must not take the thread with it.
                        Ok(job) => drop(std::panic::catch_unwind(std::panic::AssertUnwindSafe(job))),
                        Err(_) => return,
                    }
                })
                .context("starting password hashing threads")?;
        }
        Ok(Self { jobs })
    }

    fn spawn(&self, job: impl FnOnce() + Send + 'static) {
        // Fails only once every thread has gone, which cannot happen while
        // `self` holds the sender; the job, and its result sender, are then
        // dropped and the check fails.
        let _ = self.jobs.send(Box::new(job));
    }
}

/// Removes a verification entry even if the request is cancelled while waiting.
struct InflightGuard {
    auth: Arc<Authenticator>,
    tag: CacheTag,
    lock: Arc<tokio::sync::Mutex<()>>,
}

impl Drop for InflightGuard {
    fn drop(&mut self) {
        let mut inflight = self.auth.inflight.lock().unwrap();
        if Arc::strong_count(&self.lock) == 2 {
            inflight.remove(&self.tag);
        }
    }
}

/// Counts a connection's pending verification until dropped.
struct PendingGuard<'a>(&'a AtomicUsize);

impl<'a> PendingGuard<'a> {
    /// Counts one more pending verification, unless the connection already
    /// has as many as it may.
    fn charge(pending: &'a AtomicUsize) -> Option<Self> {
        if pending.fetch_add(1, Ordering::Relaxed) >= PENDING_PER_CONNECTION {
            pending.fetch_sub(1, Ordering::Relaxed);
            return None;
        }
        Some(Self(pending))
    }
}

impl Drop for PendingGuard<'_> {
    fn drop(&mut self) {
        self.0.fetch_sub(1, Ordering::Relaxed);
    }
}

fn parse_expiry(text: &str) -> Result<SystemTime> {
    let t = chrono::DateTime::parse_from_rfc3339(text.trim())
        .with_context(|| format!("expires = {text:?} is not an RFC 3339 time such as 2027-01-31T00:00:00Z"))?;
    Ok(t.with_timezone(&chrono::Utc).into())
}

/// Checks one configured user entry.
pub fn validate_entry(u: &UserEntry) -> Result<()> {
    validate_user_name(&u.name)?;
    ensure!(
        u.password_hash.is_some() || u.certificate_sha256.is_some(),
        "user {} needs a password_hash, a certificate_sha256, or both",
        u.name
    );
    if let Some(h) = &u.password_hash {
        validate_hash(h)?;
    }
    if let Some(c) = &u.certificate_sha256 {
        parse_fingerprint(c)?;
    }
    if let Some(e) = &u.expires {
        parse_expiry(e)?;
    }
    Ok(())
}

impl Authenticator {
    pub fn new(users: &[UserEntry]) -> Result<Self> {
        let slots = std::thread::available_parallelism().map_or(2, |n| n.get()) * 2;
        let auth = Self {
            users: RwLock::new(Users::default()),
            slots: Arc::new(Semaphore::new(slots)),
            hashers: HashThreads::new(slots)?,
            dummy_slow: parse_hash(&hash_password(&generate_password())?)?,
            dummy_fast: parse_hash(&hash_generated_secret(&generate_password())?)?,
            cache_key: ring::hmac::Key::new(ring::hmac::HMAC_SHA256, &random_bytes::<32>()),
            cache: Mutex::default(),
            inflight: Mutex::default(),
            attempts: PerIp::new(ATTEMPT_RATE, ATTEMPT_BURST, ATTEMPT_CLIENTS),
            generation: watch::Sender::new(0),
        };
        auth.replace(users)?;
        Ok(auth)
    }

    /// Installs a new user list. Cached verifications of users who are
    /// unchanged survive, so a reload does not make every device verify
    /// again; everything else is forgotten.
    pub fn replace(&self, entries: &[UserEntry]) -> Result<()> {
        let mut users = Users::default();
        for u in entries {
            validate_entry(u)?;
            let certificate = u.certificate_sha256.as_deref().map(parse_fingerprint).transpose()?;
            if let Some(fp) = certificate {
                ensure!(
                    users.by_certificate.insert(fp, u.name.clone()).is_none(),
                    "certificate of user {} is used twice",
                    u.name
                );
            }
            let password = u.password_hash.as_ref().map(|h| parse_hash(h).map(|p| (h.clone(), p))).transpose()?;
            let expires = u.expires.as_deref().map(parse_expiry).transpose()?;
            users.accounts.insert(u.name.clone(), Account { password, certificate, expires });
        }
        let passwords: Vec<&Hash> = users.accounts.values().filter_map(|a| a.password.as_ref().map(|p| &p.1)).collect();
        users.fast_dummy = !passwords.is_empty() && passwords.iter().all(|h| matches!(h, Hash::Pbkdf2 { .. }));
        let mut current = self.users.write().unwrap();
        *current = users;
        self.cache.lock().unwrap().retain(|_, c| c.user.as_ref().is_some_and(|u| current.holds(u)));
        self.generation.send_modify(|g| *g += 1);
        Ok(())
    }

    /// Changes whenever the user list is replaced.
    pub fn changes(&self) -> watch::Receiver<u64> {
        self.generation.subscribe()
    }

    /// Whether `user` is still configured with the same credential and has
    /// not expired.
    pub fn is_current(&self, user: &User) -> bool {
        self.users.read().unwrap().holds(user)
    }

    /// The cache key of a header value.
    pub fn tag(&self, header: &[u8]) -> CacheTag {
        ring::hmac::sign(&self.cache_key, header).as_ref().try_into().expect("SHA-256 size")
    }

    /// The user a client certificate (by fingerprint) belongs to.
    pub fn verify_certificate(&self, fp: &[u8; 32]) -> Option<User> {
        let users = self.users.read().unwrap();
        let name = users.by_certificate.get(fp)?;
        let account = users.accounts.get(name)?;
        account.live().then(|| User {
            name: name.clone(),
            credential: format!("sha256:{}", fingerprint_hex(fp)),
            expires: account.expires,
        })
    }

    /// A cached result, extending a verified one's lifetime.
    fn cached(&self, tag: &CacheTag) -> Option<Option<User>> {
        // Serialize lookup with replacement and cache invalidation.
        let users = self.users.read().unwrap();
        let mut cache = self.cache.lock().unwrap();
        let now = Instant::now();
        let entry = cache.get_mut(tag).filter(|c| c.until > now)?;
        match &entry.user {
            Some(user) if users.holds(user) => {
                entry.until = now + CACHE_TTL;
                Some(Some(user.clone()))
            }
            // Expired since it was cached.
            Some(_) => {
                cache.remove(tag);
                None
            }
            None => Some(None),
        }
    }

    fn remember(&self, tag: CacheTag, user: Option<User>) {
        let ttl = if user.is_some() { CACHE_TTL } else { NEGATIVE_TTL };
        let mut cache = self.cache.lock().unwrap();
        if cache.len() >= CACHE_MAX {
            let now = Instant::now();
            cache.retain(|_, c| c.until > now);
            if cache.len() >= CACHE_MAX {
                // Rejections must not push out verified headers, or a flood
                // of wrong credentials would make every device hash again.
                if user.is_none() {
                    return;
                }
                cache.retain(|_, c| c.user.is_some());
                if cache.len() >= CACHE_MAX {
                    cache.clear();
                }
            }
        }
        cache.insert(tag, Cached { user, until: Instant::now() + ttl });
    }

    /// Checks an Authorization or Proxy-Authorization header value. Only
    /// requests that carry new credentials pay for a hash verification, and
    /// those are limited per client and per connection.
    pub async fn verify(self: &Arc<Self>, authorization: Option<&[u8]>, client: &Client<'_>) -> Result<User, Denied> {
        let header = authorization.ok_or(Denied::Missing)?;
        let (name, password) = parse_basic(header).ok_or(Denied::Malformed)?;
        let tag = self.tag(header);
        let bound = client.bound.lock().unwrap().clone();
        if let Some((t, user)) = bound {
            if t == tag && self.is_current(&user) {
                return Ok(user);
            }
        }
        if let Some(result) = self.cached(&tag) {
            return match result {
                Some(user) => {
                    *client.bound.lock().unwrap() = Some((tag, user.clone()));
                    Ok(user)
                }
                None => Err(Denied::Rejected { user: name }),
            };
        }
        let (lock, joined) = {
            let mut inflight = self.inflight.lock().unwrap();
            match inflight.get(&tag) {
                Some(lock) => (lock.clone(), true),
                None if inflight.len() >= CACHE_MAX => return Err(Denied::Throttled { user: name }),
                None => (inflight.entry(tag).or_default().clone(), false),
            }
        };
        let cleanup = InflightGuard { auth: self.clone(), tag, lock };
        // Waiting for someone else's verification of the same header costs
        // nothing, so only a request that starts one counts as pending: a
        // device opening many tunnels at once with new credentials is fine.
        let mut pending = None;
        if !joined {
            pending =
                Some(PendingGuard::charge(client.pending).ok_or_else(|| Denied::Throttled { user: name.clone() })?);
        }
        let _guard = cleanup.lock.lock().await;
        if let Some(result) = self.cached(&tag) {
            return match result {
                Some(user) => {
                    *client.bound.lock().unwrap() = Some((tag, user.clone()));
                    Ok(user)
                }
                None => Err(Denied::Rejected { user: name }),
            };
        }
        // The verification this request waited for left nothing in the cache
        // (the user list changed meanwhile), so it has to hash after all.
        if pending.is_none() {
            pending =
                Some(PendingGuard::charge(client.pending).ok_or_else(|| Denied::Throttled { user: name.clone() })?);
        }
        let _pending = pending;
        // Only now is there real work to do: charge it to the client.
        if !self.attempts.allow(client.ip) {
            return Err(Denied::Throttled { user: name });
        }
        let generation = *self.generation.borrow();
        let result = self.verify_uncached(name.clone(), password).await;
        // Hold the user lock through the generation check and cache insertion:
        // replacement must not clear the cache between these two operations.
        let users = self.users.read().unwrap();
        // A user removed or changed meanwhile is rejected; a reload that left
        // this user alone does not fail the request, it only keeps the result
        // out of the cache.
        let result = result.filter(|u| users.holds(u));
        if *self.generation.borrow() == generation {
            self.remember(tag, result.clone());
        }
        drop(users);
        match result {
            Some(user) => {
                *client.bound.lock().unwrap() = Some((tag, user.clone()));
                Ok(user)
            }
            None => Err(Denied::Rejected { user: name }),
        }
    }

    async fn verify_uncached(&self, name: String, password: String) -> Option<User> {
        let (known, hash) = {
            let users = self.users.read().unwrap();
            let account = users.accounts.get(&name);
            let known = account.and_then(|a| a.password.clone().map(|(s, _)| (s, a.expires)));
            let hash = match account.and_then(|a| a.password.as_ref()) {
                Some((_, h)) => h.clone(),
                None if users.fast_dummy => self.dummy_fast.clone(),
                None => self.dummy_slow.clone(),
            };
            (known, hash)
        };
        let permit = self.slots.clone().acquire_owned().await.ok()?;
        let (done, result) = tokio::sync::oneshot::channel();
        self.hashers.spawn(move || {
            // Cancellation of the HTTP request must not release the slot
            // while this non-cancellable computation is still running.
            let _permit = permit;
            let _ = done.send(verify_hash(&password, &hash));
        });
        let ok = result.await.unwrap_or(false);
        let (credential, expires) = known?;
        ok.then_some(User { name, credential, expires })
    }
}

