#!/usr/bin/env python3
"""Write a transport-only copy of an unsigned, single-hop Network Relay profile."""

import argparse
import os
from pathlib import Path
import plistlib
import tempfile
from urllib.parse import urlsplit
from xml.etree import ElementTree
from xml.parsers.expat import ExpatError

MAX_SIZE = 512 * 1024
URL_KEYS = {"h2": "HTTP2RelayURL", "h3": "HTTP3RelayURL"}


def select_transport(source, transport):
    if len(source) > MAX_SIZE:
        raise ValueError("The input exceeds the 512 KiB profile limit.")
    try:
        profile = plistlib.loads(source)
    except (plistlib.InvalidFileException, ValueError, TypeError, OverflowError,
            ExpatError) as error:
        raise ValueError("Expected an unsigned XML or binary configuration profile.") from error
    if not isinstance(profile, dict) or profile.get("PayloadType") != "Configuration":
        raise ValueError("Expected an Apple configuration profile.")
    contents = profile.get("PayloadContent")
    if not isinstance(contents, list):
        raise ValueError("Expected a list of configuration payloads.")
    managed = [p for p in contents if isinstance(p, dict) and p.get("PayloadType") == "com.apple.relay.managed"]
    if len(managed) != 1:
        raise ValueError("Expected exactly one managed Relay payload.")
    hops = managed[0].get("Relays")
    if not isinstance(hops, list) or len(hops) != 1 or not isinstance(hops[0], dict):
        raise ValueError("Expected one relay hop, as generated by the project.")
    hop = hops[0]
    selected = URL_KEYS[transport]
    other = URL_KEYS["h2" if transport == "h3" else "h3"]
    url = hop.get(selected, hop.get(other))
    if not isinstance(url, str):
        raise ValueError("The relay has no usable endpoint for this transport.")
    try:
        endpoint = urlsplit(url)
        valid = (endpoint.scheme == "https" and endpoint.hostname and endpoint.username is None
                 and endpoint.password is None and endpoint.port != 0)
    except ValueError:
        valid = False
    if not valid:
        raise ValueError("Expected a relay HTTPS URL without embedded credentials.")
    hop[selected] = url
    hop.pop(other, None)

    if source.startswith(b"bplist00"):
        result = plistlib.dumps(profile, fmt=plistlib.FMT_BINARY, sort_keys=False)
    else:
        result = plistlib.dumps(profile, sort_keys=False)
        if len(result) > MAX_SIZE:
            # Selected-domain installers can already occupy most of the profile limit.
            # Remove formatting between elements while retaining literal string whitespace.
            root = ElementTree.fromstring(result)
            for node in root.iter():
                if node.tag in ("plist", "array", "dict"):
                    node.text = None
                    for child in node:
                        child.tail = None
            result = result[:result.index(b"<plist")] + ElementTree.tostring(root, encoding="utf-8") + b"\n"
    if len(result) > MAX_SIZE:
        raise ValueError("The resulting profile exceeds 512 KiB.")
    return result


def write_copy(source, destination, transport):
    with source.open("rb") as handle:
        data = select_transport(handle.read(MAX_SIZE + 1), transport)
    # Publish only a complete 0600 file. link() refuses an existing path,
    # including the source itself, without a race between checking and writing.
    with tempfile.NamedTemporaryFile(dir=destination.parent, prefix=".relay-profile-") as temp:
        os.fchmod(temp.fileno(), 0o600)
        temp.write(data)
        temp.flush()
        os.fsync(temp.fileno())
        os.link(temp.name, destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("transport", choices=URL_KEYS)
    parser.add_argument("source", type=Path, help="existing unsigned .mobileconfig")
    parser.add_argument("destination", type=Path, help="new private output file")
    args = parser.parse_args()
    try:
        write_copy(args.source, args.destination, args.transport)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Could not create the profile: {error}\n")


if __name__ == "__main__":
    main()
